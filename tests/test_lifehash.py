@pytest.mark.parametrize("fingerprint,expected_hash", VECTORS.items())
def test_matches_reference_rgb_vector(fingerprint, expected_hash):
    image = fingerprint_lifehash(fingerprint)
    assert image.mode == "RGB"
    assert image.size == (32, 32)
    assert sha256(image.tobytes()).hexdigest() == expected_hash


# Independent exact-bit values generated by bc-lifehash at the revision above,
# compiled with -std=c++17 -O3 -ffp-contract=off. Copied from the pinned fixture:
# https://github.com/w-s-bitcoin/toucan/blob/ea3958dabb00ac203a025fe9fb1fbf4b9ba0c78f/src/test/resources/com/sparrowwallet/toucan/numeric-reference.txt
# Only luminance and modulo with divisor 1 apply to this v2 fingerprint helper.
@pytest.mark.parametrize("color,expected", [
    (("0x1.999999999999ap-4", "0x1.999999999999ap-3", "0x1.3333333333333p-2"), "0x1.01ceb2p-3"),
    (("0x1p+0", "0x1p+0", "0x1p+0"), "0x1.564cdep-1"),
    (("0x0p+0", "0x0p+0", "0x0p+0"), "0x0p+0"),
], ids=["mixed", "white-separate-rounding", "black"])
def test_luminance_matches_reference_bits(color, expected):
    actual = _luminance(tuple(float.fromhex(channel) for channel in color))
    assert pack(">d", actual) == pack(">d", float.fromhex(expected))


@pytest.mark.parametrize("value,expected", [
    ("0x1.fffffffffffffp-1", "0x0p+0"),
    ("0x1.fffffdfc9a9adp-1", "0x0p+0"),
    ("-0x1p-2", "0x1.8p-1"),
    ("0x1.4p+0", "0x1p-2"),
], ids=["first-float-rounding", "second-float-rounding", "negative", "positive"])
def test_modulo_matches_reference_bits(value, expected):
    assert pack(">d", _modulo(float.fromhex(value))) == pack(">d", float.fromhex(expected))


@pytest.mark.parametrize("fingerprint", [
    "", "abcd", "123456789", "z1234567", "0x12345678", " 12345678",
    "12345678 ", "1234 678", "１２３４５６７８", "1234567\n", None, b"12345678", 12345678,
])
def test_rejects_incomplete_or_nonhex_fingerprints(fingerprint):
    with pytest.raises(ValueError, match="eight hexadecimal digits"):
        fingerprint_lifehash(fingerprint)


@pytest.mark.parametrize("size", [0, -1, 1.5, "32", True, None])
def test_rejects_invalid_sizes(size):
    with pytest.raises(ValueError, match="positive integer"):
        fingerprint_lifehash("73c5da0a", size=size)


def test_upscaling_preserves_every_source_pixel():
    canonical = fingerprint_lifehash("73c5da0a")
    scaled = fingerprint_lifehash("73c5da0a", size=64)
    assert scaled.size == (64, 64)
    for y in range(32):
        for x in range(32):
            for dy in (0, 1):
                for dx in (0, 1):
                    assert scaled.getpixel((2 * x + dx, 2 * y + dy)) == canonical.getpixel((x, y))


def test_constrained_size_uses_nearest_neighbor_resampling():
    canonical = fingerprint_lifehash("73c5da0a")
    scaled = fingerprint_lifehash("73c5da0a", size=24)
    assert scaled.size == (24, 24)
    assert scaled.tobytes() == canonical.resize((24, 24), Image.Resampling.NEAREST).tobytes()


def test_cached_images_cannot_be_changed_by_the_caller():
    first = fingerprint_lifehash("73c5da0a")
    first.paste("black", (0, 0, 32, 32))
    second = fingerprint_lifehash("73c5da0a")
    assert second is not first
    assert sha256(second.tobytes()).hexdigest() == VECTORS["73c5da0a"]


def test_cache_uses_public_fingerprint_bytes_independent_of_case_or_size():
    _fingerprint_rgb.cache_clear()
    lower = fingerprint_lifehash("73c5da0a")
    upper = fingerprint_lifehash("73C5DA0A")
    fingerprint_lifehash("73C5DA0A", size=64)
    assert lower.tobytes() == upper.tobytes()
    info = _fingerprint_rgb.cache_info()
    assert info.currsize == 1
    assert info.misses == 1
    assert info.hits == 2


def test_cache_is_bounded():
    _fingerprint_rgb.cache_clear()
    for value in range(32):
        fingerprint_lifehash(f"{value:08x}")
    info = _fingerprint_rgb.cache_info()
    assert info.maxsize == 16
    assert info.currsize == 16
